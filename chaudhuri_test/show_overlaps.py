# Colors for each camera polygon (BGR)
camera_colors = {
    "8005": (0, 0, 255),   # Red
    "8006": (0, 255, 0),   # Green
    "8007": (255, 0, 0),   # Blue
    "8008": (0, 192, 255), # Yellow
}

# Image size and scale
grid_scale = 800
background_color = (255, 255, 255)

def pixel_to_world(H, u, v):
    pt = np.array([u, v, 1.0]).reshape(3, 1)
    world_pt = H @ pt
    world_pt /= world_pt[2, 0]
    return world_pt[0, 0], world_pt[1, 0]

def main():
    # Create blank white image
    img = np.full((grid_scale, grid_scale, 3), background_color, dtype=np.uint8)

    for cam_id, data in camera_data.items():
        cam_coords = data["camera_coords"]
        world_coords = data["world_coords"]

        # Compute homography (camera → world)
        H, _ = cv2.findHomography(cam_coords, world_coords)

        # Camera frame corners in pixel coordinates
        frame_corners = np.array([
            [0, 0],
            [1280, 0],
            [1280, 720],
            [0, 720]
        ], dtype=np.float32)

        # Convert corners to world coords using homography
        world_corners = []
        for (cx, cy) in frame_corners:
            wx, wy = pixel_to_world(H, cx, cy)
            world_corners.append((wx, wy))

        # Scale and flip Y axis for image coordinates
        pts = []
        for wx, wy in world_corners:
            gx = int(wx * grid_scale)
            gy = grid_scale - int(wy * grid_scale)
            pts.append([gx, gy])
        pts = np.array(pts, dtype=np.int32)

        # --- Fill region with transparent color on separate overlay ---
        overlay = img.copy()
        cv2.fillPoly(overlay, [pts], color=camera_colors[cam_id])
        img = cv2.addWeighted(overlay, 0.2, img, 0.8, 0)

        # Draw polygon border
        cv2.polylines(img, [pts], isClosed=True, color=camera_colors[cam_id], thickness=3)

        # Label camera
        cv2.putText(img, cam_id, (pts[0][0]+5, pts[0][1]-5),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.8, camera_colors[cam_id], 2)

    # Show result
    cv2.imshow("Global World Grid", img)
    print("Press 'q' to exit.")
    while True:
        if cv2.waitKey(1) & 0xFF == ord('q'):
            break
    cv2.destroyAllWindows()

if __name__ == "__main__":
    main()